#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import ts from 'typescript'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, '..')

const lessonsRoot = path.join(repoRoot, 'src', 'data', 'course', 'en')
const mapFile = path.join(repoRoot, 'src', 'data', 'lexicon', 'enToTupi.map.ts')

const normalizeForKey = (value) => {
  const cleaned = value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]+/g, ' ')
    .trim()
    .replace(/\s+/g, '_')

  return cleaned || 'empty'
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const inlineComment = (value) => value.replace(/\s+/g, ' ').trim().replace(/\*\//g, '*\\/')

const walkFiles = (dir) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const out = []

  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walkFiles(full))
      continue
    }
    if (entry.isFile() && full.endsWith('.ts') && !full.endsWith('.d.ts')) {
      out.push(full)
    }
  }

  return out.sort()
}

const getStringLiteral = (node) => {
  if (!node) {
    return null
  }
  if (ts.isStringLiteralLike(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    return node.text
  }
  return null
}

const readExistingMap = (filePath) => {
  if (!fs.existsSync(filePath)) {
    return new Map()
  }

  const source = fs.readFileSync(filePath, 'utf8')
  const sf = ts.createSourceFile(filePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const out = new Map()

  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === 'enToTupiMap') {
      const init = node.initializer
      if (init && ts.isObjectLiteralExpression(init)) {
        for (const prop of init.properties) {
          if (!ts.isPropertyAssignment(prop)) {
            continue
          }

          let key = null
          if (ts.isStringLiteralLike(prop.name) || ts.isNoSubstitutionTemplateLiteral(prop.name)) {
            key = prop.name.text
          } else if (ts.isIdentifier(prop.name)) {
            key = prop.name.text
          }
          if (!key) {
            continue
          }

          const value = getStringLiteral(prop.initializer)
          if (value == null) {
            continue
          }

          out.set(key, value)
        }
      }
    }
    ts.forEachChild(node, visit)
  }

  visit(sf)
  return out
}

const collectEnglishEntries = (rootDir) => {
  const files = walkFiles(rootDir)
  const entries = new Map()

  for (const filePath of files) {
    const source = fs.readFileSync(filePath, 'utf8')
    const sf = ts.createSourceFile(filePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)

    const visit = (node) => {
      if (ts.isCallExpression(node)) {
        const callee = node.expression
        let calleeName = null

        if (ts.isIdentifier(callee)) {
          calleeName = callee.text
        } else if (ts.isPropertyAccessExpression(callee) && ts.isIdentifier(callee.name)) {
          calleeName = callee.name.text
        }

        if (calleeName === 'en' || calleeName === 'enText') {
          const sourceValue = getStringLiteral(node.arguments[0])
          if (sourceValue != null) {
            const explicitKey = getStringLiteral(node.arguments[1])
            const key = explicitKey ?? `en:${normalizeForKey(sourceValue)}`
            if (!entries.has(key)) {
              entries.set(key, sourceValue)
            }
          }
        }

        if (calleeName === 'localizeText') {
          const sourceValue = getStringLiteral(node.arguments[0])
          const langValue = getStringLiteral(node.arguments[1])
          if (sourceValue != null && langValue === 'en') {
            const explicitKey = getStringLiteral(node.arguments[2])
            const key = explicitKey ?? `en:${normalizeForKey(sourceValue)}`
            if (!entries.has(key)) {
              entries.set(key, sourceValue)
            }
          }
        }
      }

      ts.forEachChild(node, visit)
    }

    visit(sf)
  }

  return entries
}

const generateMapSource = (lessonEntries, existingMap) => {
  const lessonKeys = [...lessonEntries.keys()].sort((a, b) => a.localeCompare(b))
  const extraKeys = [...existingMap.keys()].filter((key) => !lessonEntries.has(key)).sort((a, b) => a.localeCompare(b))

  const lines = []
  lines.push("import type { EnToTupiMap } from '@/data/lexicon/types'")
  lines.push('')
  lines.push('// Auto-generated by `make generate-englishtotupi-map`.')
  lines.push('// Fill values with Tupi translations. Empty strings mean "pending translation".')
  lines.push('// Keys default to "en:<normalized_term_or_phrase>" unless explicitly set in lesson data.')
  lines.push('export const enToTupiMap: EnToTupiMap = {')

  for (const key of lessonKeys) {
    const source = lessonEntries.get(key) ?? ''
    const value = existingMap.get(key) ?? ''
    lines.push(`  ${quote(key)}: ${quote(value)}, // ${inlineComment(source)}`)
  }

  if (extraKeys.length > 0) {
    lines.push('')
    lines.push('  // Manual/legacy keys not currently referenced by lessons:')
    for (const key of extraKeys) {
      const value = existingMap.get(key) ?? ''
      lines.push(`  ${quote(key)}: ${quote(value)},`)
    }
  }

  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

const ensureDir = (filePath) => {
  const dir = path.dirname(filePath)
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true })
  }
}

const run = () => {
  if (!fs.existsSync(lessonsRoot)) {
    throw new Error(`Lessons directory not found: ${lessonsRoot}`)
  }

  const lessonEntries = collectEnglishEntries(lessonsRoot)
  const existingMap = readExistingMap(mapFile)
  const next = generateMapSource(lessonEntries, existingMap)

  ensureDir(mapFile)

  const previous = fs.existsSync(mapFile) ? fs.readFileSync(mapFile, 'utf8') : ''
  if (previous === next) {
    console.log('enToTupi map already up to date.')
    return
  }

  fs.writeFileSync(mapFile, next, 'utf8')
  console.log(`Generated ${path.relative(repoRoot, mapFile)} with ${lessonEntries.size} lesson keys.`)
}

run()
